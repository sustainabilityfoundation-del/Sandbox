export function toolDefinition(name: string): ToolDefinition | undefined {
  return TOOLS.find((t) => t.name === name)
}

/** Validates a value against the JSON Schema subset used by TOOLS. Returns problems (empty = valid). */
export function validateAgainst(schema: JsonSchema, value: unknown, path = 'input'): string[] {
  if (schema.$ref) {
    const name = schema.$ref.replace('#/$defs/', '')
    const target = DEFS[name]
    if (!target) return [`${path}: unknown schema ${schema.$ref}`]
    return validateAgainst(target, value, path)
  }
  if (schema.oneOf) return schema.oneOf.some((s) => !validateAgainst(s, value, path).length) ? [] : [`${path}: matches none of the allowed shapes`]
  const problems: string[] = []
  if (schema.enum && !schema.enum.includes(value)) return [`${path}: must be one of ${schema.enum.join(', ')}`]
  switch (schema.type) {
    case 'object': {
      if (typeof value !== 'object' || value === null || Array.isArray(value)) return [`${path}: must be an object`]
      const obj = value as Record<string, unknown>
      for (const k of schema.required ?? []) if (obj[k] === undefined || obj[k] === null) problems.push(`${path}.${k}: is required`)
      for (const [k, v] of Object.entries(obj)) {
        const prop = schema.properties?.[k]
        if (prop) problems.push(...validateAgainst(prop, v, `${path}.${k}`))
        else if (schema.additionalProperties === false) problems.push(`${path}.${k}: is not allowed`)
        else if (typeof schema.additionalProperties === 'object') problems.push(...validateAgainst(schema.additionalProperties, v, `${path}.${k}`))
      }
      break
    }
    case 'array':
      if (!Array.isArray(value)) return [`${path}: must be a list`]
      if (schema.minItems !== undefined && value.length < schema.minItems) problems.push(`${path}: needs at least ${schema.minItems} item(s)`)
      if (schema.maxItems !== undefined && value.length > schema.maxItems) problems.push(`${path}: allows at most ${schema.maxItems} item(s)`)
      if (schema.items) value.forEach((v, i) => problems.push(...validateAgainst(schema.items!, v, `${path}[${i}]`)))
      break
    case 'string':
      if (typeof value !== 'string') return [`${path}: must be text`]
      if (schema.maxLength !== undefined && value.length > schema.maxLength) problems.push(`${path}: is longer than ${schema.maxLength} characters`)
      break
    case 'number':
    case 'integer':
      if (typeof value !== 'number' || !Number.isFinite(value) || (schema.type === 'integer' && !Number.isInteger(value))) return [`${path}: must be ${schema.type === 'integer' ? 'an integer' : 'a number'}`]
      if (schema.minimum !== undefined && value < schema.minimum) problems.push(`${path}: must be at least ${schema.minimum}`)
      if (schema.maximum !== undefined && value > schema.maximum) problems.push(`${path}: must be at most ${schema.maximum}`)
      break
    case 'boolean':
      if (typeof value !== 'boolean') return [`${path}: must be true or false`]
      break
  }
  return problems
}
