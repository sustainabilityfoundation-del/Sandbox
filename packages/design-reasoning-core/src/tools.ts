/**
 * Provider-independent tool definitions (ai-tools.md). Plain data: name, version, title, description,
 * effect class, JSON Schema (2020-12 subset) for input and output. A provider adapter in the AI Interface
 * translates them; the AI Interface registers them as a headless contribution later (CR-A2).
 */
export type JsonSchema = {
  type?: 'object' | 'string' | 'number' | 'integer' | 'boolean' | 'array'
  properties?: Record<string, JsonSchema>
  required?: string[]
  additionalProperties?: boolean | JsonSchema
  items?: JsonSchema
  enum?: unknown[]
  maxLength?: number
  minimum?: number
  maximum?: number
  minItems?: number
  maxItems?: number
  oneOf?: JsonSchema[]
  $ref?: string
  description?: string
  default?: unknown
}

export interface ToolDefinition {
  name: string
  version: string
  title: string
  description: string
  /** query: reads; query-recorded: reads and records an invocation; draft: returns a ProposalDraft. */
  effect: 'query' | 'query-recorded' | 'draft'
  inputSchema: JsonSchema
  outputSummary: string
}

