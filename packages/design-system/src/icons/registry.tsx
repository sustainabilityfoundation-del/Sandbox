/**
 * Custom specialist icon with the same interface as a Phosphor icon (256-unit
 * grid, currentColor, regular / duotone / fill weights). A SysML block: a
 * rectangle with a compartment line and a «» stereotype mark.
 */
const SysmlBlockIcon = forwardRef<SVGSVGElement, IconProps>(function SysmlBlockIcon(
  { size = '1em', color = 'currentColor', weight = 'regular', mirrored, alt, children, ...rest },
  ref,
) {
  const stroke = weight === 'bold' ? 20 : weight === 'light' || weight === 'thin' ? 10 : 16
  return (
    <svg
      ref={ref}
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 256 256"
      fill="none"
      stroke={color}
      strokeWidth={stroke}
      strokeLinecap="round"
      strokeLinejoin="round"
      transform={mirrored ? 'scale(-1, 1)' : undefined}
      {...rest}
    >
      {alt && <title>{alt}</title>}
      {children}
      {(weight === 'duotone' || weight === 'fill') && (
        <rect x="40" y="48" width="176" height="160" rx="12" fill={color} stroke="none" opacity={weight === 'fill' ? 1 : 0.2} />
      )}
      <rect x="40" y="48" width="176" height="160" rx="12" />
      <line x1="40" y1="104" x2="216" y2="104" />
      <path d="M104 64 L92 76 L104 88 M152 64 L164 76 L152 88" stroke={weight === 'fill' ? 'var(--ws-surface, #fff)' : color} />
    </svg>
  )
})

export interface IconEntry {
  icon: PhosphorIcon
  /** Default weight: duotone for tools and object categories, regular for actions and status. */
  weight: Extract<IconWeight, 'regular' | 'duotone'>
  mirrored?: boolean
}

const tool = (icon: PhosphorIcon): IconEntry => ({ icon, weight: 'duotone' })
const action = (icon: PhosphorIcon, mirrored?: boolean): IconEntry => ({ icon, weight: 'regular', mirrored })

