/** How a semantic icon renders by default. */
export type IconWeight = 'thin' | 'light' | 'regular' | 'bold' | 'fill' | 'duotone'

export interface IconEntry {
  icon: LucideIcon
  /**
   * Role: duotone for tools and object categories, regular for actions and status. With Lucide both draw the
   * same stroke (consistent weight across the interface); the role is kept so states and future glyph sets
   * can distinguish objects from actions.
   */
  weight: Extract<IconWeight, 'regular' | 'duotone'>
  mirrored?: boolean
  /** A custom engineering glyph (same interface as the library icons). */
  custom?: boolean
}

const tool = (icon: LucideIcon): IconEntry => ({ icon, weight: 'duotone' })
const action = (icon: LucideIcon, mirrored?: boolean): IconEntry => ({ icon, weight: 'regular', mirrored })
const custom = (icon: LucideIcon, weight: IconEntry['weight'] = 'duotone'): IconEntry => ({ icon, weight, custom: true })

