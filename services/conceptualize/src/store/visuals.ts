/**
 * Visual artifacts of Concepts (concept-visualization-contracts.md §1). A visual has immutable revisions, each
 * pinned to the exact Concept revision it shows. Layouts are rendered deterministically from the pinned
 * revision's engineering definition (no stored image); illustrations are generated by services/visualization
 * and only their job and asset references are mirrored here. "Possibly outdated" is derived on read from the
 * pinned revision and the current definition, never stored and never acted on automatically.
 */

export const VISUAL_KINDS = ['illustration', 'layout', 'mechanism', 'architecture', 'envelope-3d', 'motion'] as const
export type VisualKind = (typeof VISUAL_KINDS)[number]
export const AVAILABLE_KINDS: VisualKind[] = ['illustration', 'layout']
export const GENERATION_STATES = ['pending', 'running', 'succeeded', 'failed', 'cancelled', 'refused'] as const
export type GenerationState = (typeof GENERATION_STATES)[number]

