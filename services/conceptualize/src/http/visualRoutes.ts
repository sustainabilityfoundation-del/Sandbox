import { Type } from '@sinclair/typebox'
import type { FastifyInstance } from 'fastify'
import { addAnnotation, archiveVisual, conceptDependents, createVisual, listVisualRevisions, listVisuals, recordGeneration, requireVisual, reviseVisual, revisionStaleness } from '../store/visuals'
import { registerRoute, type HostServices, type RequestContext, type RouteSpec } from './route'
import * as S from './schemas'
import * as V from './visualSchemas'

const P = Type.Object({ projectId: Type.String({ minLength: 1, maxLength: 100 }) })
const PV = Type.Object({ projectId: Type.String(), visualId: Type.String() })
const PVR = Type.Object({ projectId: Type.String(), visualId: Type.String(), revision: Type.Integer({ minimum: 1 }) })
const PC = Type.Object({ projectId: Type.String(), conceptId: Type.String() })
const E = {
  400: { description: 'Malformed request (invalid)', schema: S.ErrorBody },
  401: { description: 'No identity (unauthenticated)', schema: S.ErrorBody },
  403: { description: 'Not entitled or role does not allow it (forbidden)', schema: S.ErrorBody },
  404: { description: 'Not found', schema: S.ErrorBody },
  409: { description: 'Revision conflict (conflict)', schema: S.ErrorBody },
  422: { description: 'Semantically invalid (invalid)', schema: S.ErrorBody },
  503: { description: 'Database not available (unavailable)', schema: S.ErrorBody },
}
const READ = { 400: E[400], 401: E[401], 403: E[403], 404: E[404], 503: E[503] }
const WRITE = { ...READ, 409: E[409], 422: E[422] }
const CONC = 'Expected revision as an ETag; alternative to expectedRevision in the body'
const body = <T>(rc: RequestContext) => rc.body as T
const base = (rc: RequestContext) => `/api/concepts/v1/projects/${rc.projectId}`

export function registerVisualRoutes(app: FastifyInstance, services: HostServices, registry: RouteSpec[]) {
  const route = (spec: RouteSpec) => registerRoute(app, services, spec, registry)
  route({
    method: 'GET', path: '/projects/{projectId}/visuals', operationId: 'listVisuals', tag: 'Visuals', summary: 'Visuals (current revisions) of the project or of some Concepts, with derived staleness', params: P,
    query: Type.Object({ conceptId: Type.Optional(Type.String({ description: 'Comma-separated Concept UUIDs' })), includeArchived: Type.Optional(Type.Boolean()) }, { additionalProperties: false }),
    permission: 'read', crossModule: true, responses: { 200: { description: 'Visuals', schema: Type.Array(V.Visual) }, ...READ },
    handler: async (rc) => {
      const q = rc.query as { conceptId?: string; includeArchived?: boolean }
      return { body: await rc.read((ctx) => listVisuals(ctx.db, rc.projectId, { conceptIds: q.conceptId ? q.conceptId.split(',').map((s) => s.trim()).filter(Boolean) : undefined, includeArchived: q.includeArchived })) }
    },
  })
  route({
    method: 'POST', path: '/projects/{projectId}/visuals', operationId: 'createVisual', tag: 'Visuals',
    summary: 'Create a visual of a Concept pinned to a Concept revision (layout: drawn from the engineering definition; illustration: generated by the visualization service)', params: P, body: V.VisualCreate,
    permission: 'author', idempotency: 'required', responses: { 201: { description: 'Created', schema: V.Visual }, ...WRITE },
    handler: async (rc) => rc.write(async (ctx) => { const v = await createVisual(ctx, body(rc)); return { status: 201, body: v, etag: v.revision, headers: { Location: `${base(rc)}/visuals/${v.id}` } } }),
  })
  route({
    method: 'GET', path: '/projects/{projectId}/visuals/{visualId}', operationId: 'getVisual', tag: 'Visuals', summary: 'Read a visual (current or an exact revision) with its annotations, generation and staleness', params: PV,
    query: Type.Object({ revision: Type.Optional(Type.Integer({ minimum: 1 })) }, { additionalProperties: false }), permission: 'read', crossModule: true, concurrency: CONC,
    responses: { 200: { description: 'Visual', schema: V.Visual }, ...READ },
    handler: async (rc) => { const v = await rc.read((ctx) => requireVisual(ctx.db, rc.projectId, rc.params.visualId, (rc.query as { revision?: number }).revision)); return { body: v, etag: v.revision } },
  })
  route({
    method: 'GET', path: '/projects/{projectId}/visuals/{visualId}/revisions', operationId: 'listVisualRevisions', tag: 'Visuals', summary: 'All revisions of a visual, each with its own annotations', params: PV,
    permission: 'read', crossModule: true, responses: { 200: { description: 'Revisions', schema: Type.Array(V.Visual) }, ...READ },
    handler: async (rc) => ({ body: await rc.read(async (ctx) => { await requireVisual(ctx.db, rc.projectId, rc.params.visualId); return listVisualRevisions(ctx.db, rc.projectId, rc.params.visualId) }) }),
  })
  route({
    method: 'POST', path: '/projects/{projectId}/visuals/{visualId}/revisions', operationId: 'reviseVisual', tag: 'Visuals',
    summary: 'New visual revision pinned to a (new) Concept revision; earlier revisions and their annotations stay', params: PV, body: V.VisualRevise,
    permission: 'author', idempotency: 'optional', concurrency: CONC, responses: { 201: { description: 'Revised', schema: V.Visual }, ...WRITE },
    handler: async (rc) => { const b = body<V.VisualReviseDto>(rc); const ex = rc.expected(b.expectedRevision); return rc.write(async (ctx) => { const v = await reviseVisual(ctx, rc.params.visualId, b, ex); return { status: 201, body: v, etag: v.revision } }) },
  })
  route({
    method: 'POST', path: '/projects/{projectId}/visuals/{visualId}/archive', operationId: 'archiveVisual', tag: 'Visuals', summary: 'Archive a visual (kept with its history)', params: PV,
    body: Type.Object({ expectedRevision: Type.Optional(Type.Integer({ minimum: 1 })), reason: Type.Optional(Type.String({ maxLength: 2000 })) }, { additionalProperties: false }),
    permission: 'author', idempotency: 'optional', concurrency: CONC, responses: { 200: { description: 'Archived', schema: V.Visual }, ...WRITE },
    handler: async (rc) => { const b = body<{ expectedRevision?: number; reason?: string }>(rc); const ex = rc.expected(b.expectedRevision); return rc.write(async (ctx) => { const v = await archiveVisual(ctx, rc.params.visualId, ex, b.reason ?? ''); return { body: v, etag: v.revision } }) },
  })
  route({
    method: 'POST', path: '/projects/{projectId}/visuals/{visualId}/revisions/{revision}/annotations', operationId: 'addVisualAnnotation', tag: 'Visuals',
    summary: 'Annotate one exact visual revision: numbered pin or rectangle (normalized), instruction, optional component', params: PVR, body: V.AnnotationCreate,
    permission: 'author', idempotency: 'optional', responses: { 201: { description: 'Created', schema: V.Annotation }, ...WRITE },
    handler: async (rc) => rc.write(async (ctx) => ({ status: 201, body: await addAnnotation(ctx, rc.params.visualId, Number(rc.params.revision), body(rc)) })),
  })
  route({
    method: 'PUT', path: '/projects/{projectId}/visuals/{visualId}/revisions/{revision}/generation', operationId: 'recordVisualGeneration', tag: 'Visuals',
    summary: 'Record the visualization job of an illustration revision (job state and asset reference; one item never affects another)', params: PVR, body: V.GenerationRecord,
    permission: 'author', idempotency: 'optional', responses: { 200: { description: 'Visual', schema: V.Visual }, ...WRITE },
    handler: async (rc) => rc.write(async (ctx) => ({ body: await recordGeneration(ctx, rc.params.visualId, Number(rc.params.revision), body(rc)) })),
  })
  route({
    method: 'GET', path: '/projects/{projectId}/concepts/{conceptId}/dependents', operationId: 'listConceptDependents', tag: 'Visuals',
    summary: 'Artifacts made from a Concept revision (visuals, handoffs) with derived "possibly outdated"', params: PC,
    permission: 'read', crossModule: true, responses: { 200: { description: 'Dependents', schema: V.Dependents }, ...READ },
    handler: async (rc) => ({ body: await rc.read((ctx) => conceptDependents(ctx.db, rc.projectId, rc.params.conceptId)) }),
  })
  route({
    method: 'GET', path: '/projects/{projectId}/concepts/{conceptId}/staleness', operationId: 'getConceptRevisionStaleness', tag: 'Visuals',
    summary: 'Whether an artifact made from a Concept revision is possibly outdated (for downstream modules, e.g. CAD documents)', params: PC,
    query: Type.Object({ revision: Type.Integer({ minimum: 1 }), purpose: Type.Optional(Type.Union([Type.Literal('layout'), Type.Literal('illustration'), Type.Literal('handoff'), Type.Literal('downstream')])) }, { additionalProperties: false }),
    permission: 'read', crossModule: true, responses: { 200: { description: 'Staleness', schema: V.Staleness }, ...READ },
    handler: async (rc) => { const q = rc.query as { revision: number; purpose?: 'layout' | 'illustration' | 'handoff' | 'downstream' }; return { body: await rc.read((ctx) => revisionStaleness(ctx.db, rc.projectId, rc.params.conceptId, q.revision, q.purpose ?? 'downstream')) } },
  })
}
