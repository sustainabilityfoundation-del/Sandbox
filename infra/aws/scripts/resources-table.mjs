// Prints the resources of the synthesized templates (cdk.out/*.template.json) as Markdown tables, one per stack, for the owner's
// approval before anything is created. Run `npm run synth` first (offline), then `npm run resources > table.md`.
// Reads only local files. The note column shows the settings that matter for cost and risk; it never prints a secret value
// (templates hold none).
import { readFileSync, readdirSync } from 'node:fs'
import path from 'node:path'

const dir = path.resolve(import.meta.dirname, '..', 'cdk.out')
const order = ['Ews-GithubOidc', 'Ews-Dev-Data', 'Ews-Dev-Migrate', 'Ews-Dev-App', 'Ews-Dev-Edge']
const files = readdirSync(dir).filter((f) => f.endsWith('.template.json')).sort((a, b) => order.indexOf(a.split('.')[0]) - order.indexOf(b.split('.')[0]))

const text = (v) => (v === undefined ? '' : typeof v === 'string' || typeof v === 'number' || typeof v === 'boolean' ? String(v) : '')
const NOTES = {
  'AWS::EC2::VPC': (p) => `CIDR ${text(p.CidrBlock)}`,
  'AWS::EC2::Subnet': (p, id) => `${/public/i.test(id) ? 'public' : 'isolated'}, CIDR ${text(p.CidrBlock)}`,
  'AWS::EC2::VPCEndpoint': (p) => `gateway endpoint (free)`,
  'AWS::EC2::InternetGateway': () => 'no NAT gateway anywhere',
  'AWS::EC2::SecurityGroup': (p) => text(p.GroupDescription),
  'AWS::RDS::DBInstance': (p) => `${text(p.Engine)} ${text(p.EngineVersion)}, ${text(p.DBInstanceClass)}, ${text(p.AllocatedStorage)} GB ${text(p.StorageType)} (max ${text(p.MaxAllocatedStorage)}), encrypted ${text(p.StorageEncrypted)}, public ${text(p.PubliclyAccessible)}, multi-AZ ${text(p.MultiAZ)}, backups ${text(p.BackupRetentionPeriod)} days, deletion protection ${text(p.DeletionProtection)}, snapshot on removal`,
  'AWS::RDS::DBParameterGroup': (p) => Object.entries(p.Parameters ?? {}).map(([k, v]) => `${k}=${v}`).join(', '),
  'AWS::SecretsManager::Secret': (p) => `${text(p.Name)} (generated value, retained on stack deletion)`,
  'AWS::EFS::FileSystem': (p) => `encrypted ${text(p.Encrypted)}, ${text(p.PerformanceMode)}, throughput ${text(p.ThroughputMode)}, automatic backup ${text(p.BackupPolicy?.Status)}, retained`,
  'AWS::EFS::AccessPoint': (p) => `path ${text(p.RootDirectory?.Path)}, uid ${text(p.PosixUser?.Uid)}`,
  'AWS::ECR::Repository': (p) => `${text(p.RepositoryName)}, ${text(p.ImageTagMutability)} tags, scan on push, keep 20 images`,
  'AWS::ECS::Cluster': (p) => text(p.ClusterName),
  'AWS::Logs::LogGroup': (p) => `${text(p.LogGroupName)}, ${text(p.RetentionInDays)} days`,
  'AWS::ECS::TaskDefinition': (p) => `${text(p.Family)}: ${text(p.Cpu)} CPU units, ${text(p.Memory)} MiB, ${text(p.RuntimePlatform?.CpuArchitecture)}`,
  'AWS::ECS::Service': (p) => `${text(p.ServiceName)}: desired ${text(p.DesiredCount) || 'set by schedule'}, Fargate, circuit breaker with rollback`,
  'AWS::ElasticLoadBalancingV2::LoadBalancer': (p) => `${text(p.Scheme)} application load balancer`,
  'AWS::ElasticLoadBalancingV2::TargetGroup': (p) => `port ${text(p.Port)}, health check ${text(p.HealthCheckPath)}`,
  'AWS::S3::Bucket': (p) => `private, block all public access, named from account and region, retained`,
  'AWS::CloudFront::Distribution': () => 'HTTPS only, price class 100, /api/* to the VPC origin, everything behind the gate',
  'AWS::CloudFront::Function': (p) => `${text(p.Name)}: ${text(p.FunctionConfig?.Runtime)}, gate and routing`,
  'AWS::CloudFront::KeyValueStore': (p) => `${text(p.Name)} (empty; the hash is set by the owner)`,
  'AWS::CloudFront::VpcOrigin': () => 'private connection to the internal load balancer',
  'AWS::CloudFront::OriginAccessControl': () => 'S3 access only through CloudFront',
  'AWS::IAM::OIDCProvider': (p) => text(p.Url),
  'AWS::IAM::Role': (p) => text(p.RoleName) || 'service role',
  'AWS::ApplicationAutoScaling::ScalableTarget': () => 'optional night schedule',
}

const clean = (s) => s.replace(/\|/g, '/').replace(/\s+/g, ' ').trim()
let total = 0
console.log('Generated by `npm run resources` from the synthesized templates; do not edit by hand.\n')
for (const f of files) {
  const t = JSON.parse(readFileSync(path.join(dir, f), 'utf8'))
  const rows = Object.entries(t.Resources ?? {}).filter(([, r]) => r.Type !== 'AWS::CDK::Metadata')
  total += rows.length
  console.log(`### ${f.replace('.template.json', '')} (${rows.length} resources)\n`)
  console.log('| Resource type | Logical ID | Settings |')
  console.log('| --- | --- | --- |')
  for (const [id, r] of rows.sort((a, b) => a[1].Type.localeCompare(b[1].Type) || a[0].localeCompare(b[0]))) {
    const note = NOTES[r.Type]?.(r.Properties ?? {}, id) ?? ''
    console.log(`| ${r.Type.replace('AWS::', '')} | \`${id}\` | ${clean(note)} |`)
  }
  console.log('')
}
console.log(`Total: ${total} resources.`)
